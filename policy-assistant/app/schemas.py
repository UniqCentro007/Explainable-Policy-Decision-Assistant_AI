from datetime import datetime
from enum import Enum

from pydantic import BaseModel, ConfigDict, Field


# --- Enums for Governance & Routing ---
class RiskLevel(str, Enum):
    LOW = "LOW"
    MEDIUM = "MEDIUM"
    HIGH = "HIGH"
    CRITICAL = "CRITICAL"


class DecisionStatus(str, Enum):
    APPROVED = "APPROVED"
    FLAGGED_FOR_REVIEW = "FLAGGED_FOR_REVIEW"
    REJECTED = "REJECTED"


# --- 1. Reasoning Components ---
class ReasoningStep(BaseModel):
    """Individual step in the AI's logical chain for RAG transparency."""

    step_number: int = Field(
        ..., description="The sequence order of the reasoning"
    )
    title: str = Field(
        ..., min_length=1, max_length=100, description="Short summary of the step"
    )
    analysis: str = Field(
        ..., description="The detailed policy logic applied in this step"
    )
    evidence: str | None = Field(
        None, description="The specific quote from documents"
    )
    source_file: str | None = Field(
        None, description="The filename retrieved from vector store"
    )


class AgentAuditMetadata(BaseModel):
    """Telemetry generated by the agent's internal Critic/Auditor node."""

    verification_passed: bool = True
    iterations: int = 1
    critique_notes: str | None = None
    risk_level: RiskLevel = RiskLevel.LOW
    requires_human_approval: bool = False


# --- 2. Main API Response ---
class PolicyResponse(BaseModel):
    """The structured output returned to the React UI."""

    model_config = ConfigDict(from_attributes=True)

    id: str | None = None
    reasoning_trace: list[ReasoningStep]
    recommendation: str
    confidence_score: float
    retrieved_sources: list[str] = Field(default_factory=list)

    # Agentic Extensions
    status: DecisionStatus = DecisionStatus.APPROVED
    audit_metadata: AgentAuditMetadata = Field(default_factory=AgentAuditMetadata)


# --- 3. Input Requests ---
class PolicyRequest(BaseModel):
    """The audit query sent from the frontend."""

    question: str = Field(..., min_length=10, max_length=1000)
    domain: str = Field(
        default="Unified", description="Target domain or Unified global index"
    )
    user_id: str = Field(default="MAGESH_DEV")


class HumanApprovalRequest(BaseModel):
    """Payload sent by a policy analyst to approve/override a flagged decision."""

    query_id: str
    reviewer_id: str
    action: str = Field(..., description="'APPROVE' or 'OVERRIDE'")
    reviewer_notes: str | None = None
    modified_recommendation: str | None = None


class LoginRequest(BaseModel):
    """Authentication credentials for the PostgreSQL verification."""

    username: str
    password: str


class FeedbackRequest(BaseModel):
    """Captures user ratings on AI clarity."""

    query_id: str
    clarity_rating: bool
    comments: str | None = None


# --- 4. History & Admin Schemas ---
class HistoryResponse(BaseModel):
    """Past audit records for the History tab."""

    model_config = ConfigDict(from_attributes=True)

    id: str
    user_id: str
    question: str
    domain: str | None = None  # Optional fallback for compatibility
    recommendation: str
    confidence_score: float
    created_at: datetime
    status: str = "APPROVED"


class AdminMetrics(BaseModel):
    """System performance data for the Manager Dashboard."""

    total_queries: int
    average_latency_seconds: float
    user_clarity_score_percent: float
    system_status: str = "Operational"
    agent_refinement_rate_percent: float = 0.0
    pending_human_reviews: int = 0